// Run with: node scripts/retail/build-seed.mjs
//
// Writes db/retail-seed-1.sql … db/retail-seed-N.sql from the deterministic
// generator (lib/retail/generate.js), split into chunks small enough to paste into
// the Supabase SQL Editor. Paste them in order, after db/retail-schema.sql.
//
// Part 1 clears every retail table and loads everything except weekly sales; the
// later parts load weekly sales. The retail_meta row goes in LAST, and the app only
// switches from its in-memory copy to Supabase once that row exists — so a
// half-finished seed is never served.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { generateDataset } from "../../lib/retail/generate.js";

const DB_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "../../db");
const CHUNK_BYTES = 350_000;
const BATCH = 400; // rows per INSERT statement

const lit = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return `ARRAY[${v.map(lit).join(",")}]::text[]`;
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const COLUMNS = {
  retail_dcs: ["dc_id", "name", "city", "state", "serves"],
  retail_stores: ["store_no", "name", "site", "city", "state", "region", "climate", "grade", "format", "sqft", "opened_on", "lat", "lng", "dc_id"],
  retail_vendors: ["vendor_id", "name", "country", "ship_mode", "promised_lead_days", "moq", "fill_rate", "notes"],
  retail_products: ["style_id", "name", "department", "category", "lifecycle", "season", "vendor_id", "unit_cost", "full_price", "launch_date", "end_date", "carryover", "size_group", "sizes", "case_pack", "presentation_min", "like_item", "current_method", "min_qty", "max_qty"],
  retail_promotions: ["promo_id", "style_id", "name", "start_date", "end_date", "discount_pct", "scope"],
  retail_sales_daily: ["store_no", "style_id", "day", "units", "on_hand_end"],
  retail_size_sales: ["store_no", "style_id", "size", "units_13w"],
  retail_store_inventory: ["store_no", "style_id", "on_hand", "in_transit", "next_delivery", "depth_target", "presentation_min", "min_qty", "max_qty", "last_alloc_qty", "by_size"],
  retail_dc_inventory: ["dc_id", "style_id", "on_hand", "on_order", "next_receipt", "note"],
  retail_purchase_orders: ["po_no", "vendor_id", "style_id", "dc_id", "qty_ordered", "qty_received", "order_date", "promised_date", "received_date", "status"],
  retail_replen_weekly: ["style_id", "week_start", "pos_units", "store_order_units", "dc_order_units"],
  retail_sales_weekly: ["store_no", "style_id", "week_start", "units", "on_hand_end", "stockout_days", "markdown_pct"],
};

function inserts(table, rows, onConflict = "") {
  const cols = COLUMNS[table];
  const out = [];
  for (let i = 0; i < rows.length; i += BATCH) {
    const values = rows.slice(i, i + BATCH).map((r) => `(${cols.map((c) => lit(r[c])).join(",")})`);
    out.push(`INSERT INTO ${table} (${cols.join(", ")}) VALUES\n${values.join(",\n")}${onConflict};\n`);
  }
  return out;
}

const ds = generateDataset();
const header = (n, total, what) =>
  `-- Generated by scripts/retail/build-seed.mjs from lib/retail/generate.js. Do not edit by hand.\n` +
  `-- Retail demo seed, part ${n} of ${total}: ${what}\n` +
  `-- Paste into the Supabase SQL Editor after db/retail-schema.sql, parts in order.\n\n`;

// part 1: everything but weekly sales, parents before children
const part1 = [
  "TRUNCATE retail_meta, retail_replen_weekly, retail_purchase_orders, retail_dc_inventory, retail_store_inventory, retail_size_sales, retail_sales_daily, retail_sales_weekly, retail_promotions, retail_products, retail_vendors, retail_stores, retail_dcs;\n",
  ...inserts("retail_dcs", ds.dcs),
  ...inserts("retail_stores", ds.stores),
  ...inserts("retail_vendors", ds.vendors),
  ...inserts("retail_products", ds.products),
  ...inserts("retail_promotions", ds.promotions),
  ...inserts("retail_sales_daily", ds.salesDaily),
  ...inserts("retail_size_sales", ds.sizeSales),
  ...inserts("retail_store_inventory", ds.storeInventory),
  ...inserts("retail_dc_inventory", ds.dcInventory),
  ...inserts("retail_purchase_orders", ds.purchaseOrders),
  ...inserts("retail_replen_weekly", ds.replenWeekly),
].join("\n");

// later parts: weekly sales, re-runnable on their own
const salesStatements = inserts("retail_sales_weekly", ds.salesWeekly, "\nON CONFLICT (store_no, style_id, week_start) DO NOTHING");
const chunks = [];
let current = [];
let size = 0;
for (const st of salesStatements) {
  if (size + st.length > CHUNK_BYTES && current.length) {
    chunks.push(current);
    current = [];
    size = 0;
  }
  current.push(st);
  size += st.length;
}
if (current.length) chunks.push(current);

const total = 1 + chunks.length;
const metaRow = `\n-- Last: the marker row the app looks for before reading from Supabase.\n` +
  `INSERT INTO retail_meta (key, value) VALUES ('retailer', ${lit(ds.meta)})\nON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;\n`;

for (const f of fs.readdirSync(DB_DIR).filter((f) => /^retail-seed-\d+\.sql$/.test(f))) fs.unlinkSync(path.join(DB_DIR, f));
const files = [[header(1, total, "stores, products, vendors, POs, inventory, launch-week and size sales") + part1]];
chunks.forEach((c, i) => {
  const last = i === chunks.length - 1;
  files.push([header(i + 2, total, `weekly sales (${i + 1}/${chunks.length})`) + c.join("\n") + (last ? metaRow : "")]);
});
files.forEach(([sql], i) => {
  const file = path.join(DB_DIR, `retail-seed-${i + 1}.sql`);
  fs.writeFileSync(file, sql);
  console.log(`${path.relative(process.cwd(), file)}  ${(sql.length / 1024).toFixed(0)} KB`);
});
console.log(`${ds.salesWeekly.length} weekly sales rows, ${ds.storeInventory.length} store positions, ${ds.purchaseOrders.length} POs`);
